async def main():
    llm = DeepSeekClient()
    print("== 情绪错判 ==")
    emo_wrong = 0
    emo_n = 0
    for label, items in EMOTION_SET.items():
        for text in items:
            emo_n += 1
            out = await judge(text, db, llm)
            if out["emotion"] != label:
                emo_wrong += 1
                print(f"  [{label}] {text} → {out['emotion']}")
    print(f"情绪：{emo_n - emo_wrong}/{emo_n} = {(emo_n - emo_wrong) / emo_n:.1%}")

    print("== 分诊错判 ==")
    tri_wrong = 0
    tri_n = 0
    for label, items in TRIAGE_SET.items():
        for text in items:
            tri_n += 1
            out = await judge(text, db, llm)
            pred = out["intent"]
            ok = pred == label or (label in ("share", "statement")
                                   and pred in ("share", "statement"))
            if not ok:
                tri_wrong += 1
                print(f"  [{label}] {text} → {pred}")
    print(f"分诊：{tri_n - tri_wrong}/{tri_n} = {(tri_n - tri_wrong) / tri_n:.1%}")


asyncio.run(main())
